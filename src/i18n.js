const LANGUAGE_STORAGE_KEY = "gluvia.language";

function getInitialLanguage() {
  if (typeof localStorage === "undefined") return "fa";
  const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return stored === "en" || stored === "fa" ? stored : "fa";
}

function applyDocumentLanguage(language) {
  if (typeof document === "undefined") return;
  const isDari = language === "fa";
  document.documentElement.lang = isDari ? "fa" : "en";
  document.documentElement.dir = isDari ? "rtl" : "ltr";
}

i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: getInitialLanguage(),
    fallbackLng: "fa",
    supportedLngs: ["fa", "en"],
    interpolation: {
      escapeValue: false,
    },
  })

applyDocumentLanguage(i18n.language);

i18n.on("languageChanged", (language) => {
  if (typeof localStorage !== "undefined") {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  }
  applyDocumentLanguage(language);
});

export default i18n;